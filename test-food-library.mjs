import assert from 'node:assert/strict';
import fs from 'node:fs';
import {searchUSDA,foodDefaults,createCustomFood,customFoodIssues,nutrientUnits} from './dist/food-library.mjs';
import {restoreFoods,preferenceIssues} from './dist/preferences.mjs';
import {buildModel,optimize,defaults,eligible,validate} from './dist/model.mjs';
const library=JSON.parse(fs.readFileSync(new URL('./dist/usda-library.json',import.meta.url)));
const base=JSON.parse(fs.readFileSync(new URL('./dist/foods.json',import.meta.url)));
assert.equal(library.foods.length,6961);
assert.equal(new Set(library.foods.map(f=>f.fdcId)).size,library.foods.length);
for(const f of library.foods)for(const k of Object.keys(nutrientUnits))assert(Number.isFinite(f.nutrients[k])&&f.nutrients[k]>=0,`${f.fdcId} ${k}`);
const wing=searchUSDA(library.foods,'chicken wings')[0];
assert.equal(wing.fdcId,'172390');assert.equal(wing.ndbId,'05100');
// Independent known record values from the official USDA data download.
assert.deepEqual(wing.nutrients,{iron:0.46,sodium:84,vitaminC:0,protein:17.52,calories:191,calcium:11,carbs:0,fibre:0,fat:12.85});
assert.equal(wing.ediblePercent,62);
assert(searchUSDA(library.foods,'salmon raw').length>0);
assert(searchUSDA(library.foods,'chickpeas').length>0);
assert(searchUSDA(library.foods,'chicken wings cooked').every(f=>/cooked/i.test(f.description)));
assert.equal(searchUSDA(library.foods,'no-such-food-xyz').length,0);
const input={...foodDefaults(wing),price:9.99,minGrams:300};
const food=createCustomFood(wing,input,'custom_test_wings');
assert.equal(food.grams*food.edibleYield,620);assert.equal(food.priceStatus,'user');
assert.equal(food.nutrients.calories,191); // never scale per-100-g nutrients by package weight
assert(eligible(food,defaults));assert(!eligible(food,{...defaults,diet:'vegetarian'}));
assert(!eligible(food,{...defaults,diet:'vegan'}));assert(eligible(food,{...defaults,dairyFree:true}));
assert(preferenceIssues([food],{...defaults,diet:'vegetarian'}).length);
const unknown=createCustomFood(wing,{...input,dietProfile:'unknown'},'custom_unknown');
for(const s of [{...defaults,diet:'vegetarian'},{...defaults,diet:'vegan'},{...defaults,diet:'no-pork'},{...defaults,dairyFree:true}])assert(!eligible(unknown,s));
assert(eligible(unknown,defaults));
for(const [key,value]of [['price',0],['price',NaN],['grams',0],['grams',Infinity],['ediblePercent',101],['ediblePercent',0],['minGrams',1001],['maxGrams',-1],['dietProfile','invalid']])assert.throws(()=>createCustomFood(wing,{...input,[key]:value},'custom_bad'));
assert.throws(()=>createCustomFood({...wing,nutrients:{calories:191}},input,'custom_missing'));
assert(customFoodIssues({...food,price:-5}).length);
const saved=restoreFoods(base,JSON.parse(JSON.stringify([{...base[0],price:3.33},food,food,{...food,id:'custom_invalid',price:null}])));
assert.equal(saved.length,base.length+1);assert.equal(saved[0].price,3.33);
assert.deepEqual(saved.find(f=>f.id===food.id),food);
const all=[...base,food],model=buildModel(all,defaults);
assert.equal(model.variables['buy_'+food.id]['supply_'+food.id],-6.2);
assert.equal(model.constraints['cap_'+food.id].min,3);
const result=optimize(all,defaults);assert.equal(result.status,'success');
const item=result.items.find(f=>f.id===food.id);assert(item);assert(item.used>=300-0.01);assert(item.packs>=1);
assert(Math.abs(item.left-(item.packs*620-item.used))<0.001);
assert.equal(item.cost,item.packs*9.99);
const reconstruction={feasible:true};for(const f of result.items){reconstruction['eat_'+f.id]=f.used/100;reconstruction['buy_'+f.id]=f.packs;}
assert(validate(model,reconstruction));
const stocked=optimize(all.map(f=>({...f,pantry:f.maxGrams})),defaults);
assert.equal(stocked.status,'success');assert.equal(stocked.total,0);assert(stocked.items.find(f=>f.id===food.id).used>=300-0.01);
const edited=createCustomFood(wing,{...input,price:5.49,grams:500,pantry:100},food.id);
assert.equal(edited.grams*edited.edibleYield,310);assert.equal(edited.pantry,100);
assert.equal(buildModel([...base,edited],defaults).variables['buy_'+food.id]['supply_'+food.id],-3.1);
const potato=createCustomFood({...wing,fdcId:'123'}, {...input,foodGroup:'Starchy'}, 'custom_potato');
assert.equal(buildModel([potato],defaults).variables.eat_custom_potato.nonstarchy,0);
console.log('PASS: USDA provenance and all nutrient values; plural search; cooked/raw matches; bone yield; custom food persistence; invalid inputs; dietary exclusions; must-includes; pack costs and pantry; edited packages; starchy vegetable rule.');
console.log('Test basket with 300 g minimum wings:',result.total.toFixed(2));
