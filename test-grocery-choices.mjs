import assert from 'node:assert/strict';
import fs from 'node:fs';
import {searchGroceries,withGroceryChoice,foodDefaults,createCustomFood,nutrientUnits} from './dist/food-library.mjs';
import {restoreFoods} from './dist/preferences.mjs';
import {optimize,defaults} from './dist/model.mjs';
const read=name=>JSON.parse(fs.readFileSync(new URL(`./dist/${name}`,import.meta.url)));
const choices=read('grocery-choices.json').choices,records=read('usda-library.json').foods,base=read('foods.json');
const reference=choice=>withGroceryChoice(records.find(r=>r.fdcId===choice.fdcId),choice);
assert.equal(choices.length,new Set(choices.map(c=>c.id)).size);
for(const c of choices){
 const r=reference(c),d=foodDefaults(r),f=createCustomFood(r,{...d,price:9.99},'custom_mapping');
 assert.equal(f.name,c.name);assert.equal(f.commonFoodId,c.id);
 assert.deepEqual(f.nutrients,r.nutrients,'Friendly labels must not change USDA nutrient values');
 for(const k of Object.keys(nutrientUnits))assert(Number.isFinite(f.nutrients[k]));
 assert.equal(f.usdaDescription,r.description);
}
assert.deepEqual(searchGroceries(choices,'salmon').map(c=>c.name),['Salmon fillet','Salmon steak','Smoked salmon','Canned salmon']);
for(const query of ['salmon fillet','salmon filets','salmon fillets'])assert.equal(searchGroceries(choices,query)[0].name,'Salmon fillet');
assert.equal(searchGroceries(choices,'salmon steak')[0].name,'Salmon steak');
assert.equal(searchGroceries(choices,'lean ground beef')[0].name,'Lean ground beef');
assert.equal(searchGroceries(choices,'extra lean ground beef')[0].name,'Extra-lean ground beef');
assert.equal(searchGroceries(choices,'beef shank')[0].name,'Beef shank');
assert(searchGroceries(choices,'beef mince').some(f=>f.name==='Lean ground beef'));
assert(searchGroceries(choices,'beef').every(f=>!/[0-9]%|separable|trimmed|grades|USDA/i.test(f.name)));
for(const [query,name]of [['chicken wings','Chicken wings'],['tofu','Firm tofu'],['blueberry','Blueberries'],['potatoes','Potatoes'],['tomato','Tomatoes'],['icecream','Vanilla ice cream']])assert.equal(searchGroceries(choices,query)[0].name,name);
assert.equal(searchGroceries(choices,'xyznotfood').length,0);
assert(searchGroceries(choices,'').length<=8);
const fillet=reference(choices.find(c=>c.name==='Salmon fillet')),steak=reference(choices.find(c=>c.name==='Salmon steak'));
assert.equal(fillet.fdcId,steak.fdcId);
assert.equal(foodDefaults(fillet).ediblePercent,100);assert.equal(foodDefaults(steak).ediblePercent,85);
assert(steak.groceryChoice.yieldNote.includes('App estimate'));
assert(steak.groceryChoice.referenceNote.includes('Atlantic'));
for(const [name,max]of [['Extra-lean ground beef',10],['Lean ground beef',17],['Medium ground beef',23],['Regular ground beef',30]])assert(reference(choices.find(c=>c.name===name)).nutrients.fat<=max);
const fish=createCustomFood(steak,{...foodDefaults(steak),price:12.99,grams:500,minGrams:200},'custom_salmon_steak');
const saved=restoreFoods(base,JSON.parse(JSON.stringify([fish]))).find(f=>f.id===fish.id);
assert.deepEqual(saved,fish);assert.equal(saved.grams*saved.edibleYield,425);
const edited=createCustomFood(steak,{...saved,ediblePercent:saved.edibleYield*100,price:10.99},saved.id);
assert.equal(edited.name,'Salmon steak');assert.equal(edited.edibleYield,0.85);assert.equal(edited.commonFoodId,fish.commonFoodId);
const result=optimize([...base,edited],defaults);assert.equal(result.status,'success');
assert(result.items.find(f=>f.id===fish.id).used>=200-0.01);
console.log('PASS: all grocery mappings; familiar beef/salmon/other names; aliases; distinct fillet and steak choices; Canadian beef categories; source disclosure; saved edits and required-food solve.');
